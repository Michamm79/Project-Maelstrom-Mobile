/** Every character the font covers, in code-point order. */
export const CHARS = Object.keys(G).sort((a, b) => a.codePointAt(0) - b.codePointAt(0));

/**
 * One glyph as a grid of booleans, padded to the full cell.
 *
 * Glyphs with no descender are written with seven rows rather than nine,
 * because two rows of dots on every letter in the file is two hundred lines of
 * nothing - and a missing row is unambiguous: it is empty.
 */
export function pixelsOf(ch) {
  const rows = G[ch].split('/');
  const grid = [];
  for (let r = 0; r < ROWS_TOTAL; r++) {
    const row = rows[r] ?? '.'.repeat(CELL_W);
    grid.push([...row].map((c) => c === '#'));
  }
  return grid;
}

